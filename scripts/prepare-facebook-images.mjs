import { mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(scriptDirectory, '..')
const archiveDirectory = path.join(root, 'facebook-archive')
const sourceDirectory = path.join(archiveDirectory, 'images')
const outputDirectory = path.join(root, 'public', 'images', 'facebook')
const fullDirectory = path.join(outputDirectory, 'full')
const thumbnailDirectory = path.join(outputDirectory, 'thumbs')
const contactSheetDirectory = path.join(archiveDirectory, 'contact-sheets')
const dataFile = path.join(root, 'src', 'facebook-archive.ts')

const manifest = JSON.parse(
  await readFile(path.join(archiveDirectory, 'manifest.json'), 'utf8'),
)
const photos = manifest.photos

await Promise.all([
  rm(outputDirectory, { recursive: true, force: true }),
  rm(contactSheetDirectory, { recursive: true, force: true }),
])
await Promise.all([
  mkdir(fullDirectory, { recursive: true }),
  mkdir(thumbnailDirectory, { recursive: true }),
  mkdir(contactSheetDirectory, { recursive: true }),
])

const concurrency = 8
let cursor = 0
let completed = 0
let originalBytes = 0
let fullImageBytes = 0
let thumbnailBytes = 0
let optimizedBytes = 0
const contactTiles = []

function webpFilename(filename) {
  return filename.replace(/\.[^.]+$/, '.webp')
}

function labelSvg(index, width = 220, height = 30) {
  const label = String(index).padStart(3, '0')
  return Buffer.from(`
    <svg width="${width}" height="${height}" xmlns="http://www.w3.org/2000/svg">
      <rect width="100%" height="100%" fill="#052b3e"/>
      <text x="12" y="21" fill="#ffffff" font-family="Arial, sans-serif" font-size="15" font-weight="700">${label}</text>
      <text x="55" y="21" fill="#9bdff1" font-family="Arial, sans-serif" font-size="11">FACEBOOK ARCHIVE</text>
    </svg>
  `)
}

async function preparePhoto(photo) {
  const sourcePath = path.join(sourceDirectory, photo.filename)
  const outputName = webpFilename(photo.filename)
  const input = sharp(sourcePath, { failOn: 'none' }).rotate()
  const sourceSize = (await stat(sourcePath)).size

  const fullBuffer = await input
    .clone()
    .resize({
      width: 1600,
      height: 1600,
      fit: 'inside',
      withoutEnlargement: true,
    })
    .webp({ quality: 78, effort: 5, smartSubsample: true })
    .toBuffer()

  const thumbnailBuffer = await input
    .clone()
    .resize({ width: 640, height: 480, fit: 'cover', position: 'attention' })
    .webp({ quality: 70, effort: 5, smartSubsample: true })
    .toBuffer()

  const contactImage = await input
    .clone()
    .resize({ width: 220, height: 150, fit: 'cover', position: 'attention' })
    .webp({ quality: 66, effort: 4 })
    .toBuffer()

  const contactTile = await sharp({
    create: {
      width: 220,
      height: 180,
      channels: 3,
      background: '#052b3e',
    },
  })
    .composite([
      { input: contactImage, left: 0, top: 0 },
      { input: labelSvg(photo.index), left: 0, top: 150 },
    ])
    .webp({ quality: 72, effort: 4 })
    .toBuffer()

  await Promise.all([
    writeFile(path.join(fullDirectory, outputName), fullBuffer),
    writeFile(path.join(thumbnailDirectory, outputName), thumbnailBuffer),
  ])

  originalBytes += sourceSize
  fullImageBytes += fullBuffer.length
  thumbnailBytes += thumbnailBuffer.length
  optimizedBytes += fullBuffer.length + thumbnailBuffer.length
  contactTiles[photo.index - 1] = contactTile
  completed += 1
  process.stdout.write(`\rPrepared ${completed}/${photos.length} Facebook images`)
}

async function worker() {
  while (true) {
    const index = cursor
    cursor += 1
    if (index >= photos.length) return
    await preparePhoto(photos[index])
  }
}

await Promise.all(Array.from({ length: concurrency }, () => worker()))
process.stdout.write('\n')

const columns = 5
const rows = 5
const perSheet = columns * rows
for (let start = 0; start < contactTiles.length; start += perSheet) {
  const tiles = contactTiles.slice(start, start + perSheet)
  const sheetNumber = Math.floor(start / perSheet) + 1
  const composites = tiles.map((input, index) => ({
    input,
    left: (index % columns) * 220,
    top: Math.floor(index / columns) * 180,
  }))

  await sharp({
    create: {
      width: columns * 220,
      height: rows * 180,
      channels: 3,
      background: '#eaf8fb',
    },
  })
    .composite(composites)
    .webp({ quality: 80, effort: 5 })
    .toFile(
      path.join(
        contactSheetDirectory,
        `facebook-contact-${String(sheetNumber).padStart(2, '0')}.webp`,
      ),
    )
}

const ids = photos.map((photo) => photo.facebookPhotoId)
const generatedSource = `// Generated by scripts/prepare-facebook-images.mjs.\n// Do not edit manually; update facebook-archive/manifest.json and rerun the script.\n\nexport const facebookArchiveIds = ${JSON.stringify(ids, null, 2)} as const\n`
await writeFile(dataFile, generatedSource, 'utf8')

const summary = {
  photos: photos.length,
  fullImages: photos.length,
  thumbnails: photos.length,
  contactSheets: Math.ceil(photos.length / perSheet),
  originalBytes,
  fullImageBytes,
  thumbnailBytes,
  optimizedBytes,
  fullImageReductionPercent:
    originalBytes > 0
      ? Number(((1 - fullImageBytes / originalBytes) * 100).toFixed(1))
      : 0,
}
await writeFile(
  path.join(outputDirectory, 'conversion-summary.json'),
  `${JSON.stringify(summary, null, 2)}\n`,
  'utf8',
)
console.log(summary)
